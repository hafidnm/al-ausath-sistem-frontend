/**
 * CSV helpers for Nilai Mapel import/export.
 *
 * Template format (per-mapel):
 *   nomor_induk,nama_santri,T1,T2,...,Tn,UH1,UH2,...,UHm,UAS
 *
 * All UH values are assumed valid (soal_disusun_pengajar=true, diawasi_pengajar=true).
 */

export interface CsvSantriRow {
  nomor_induk: string
  nama_santri: string
  tugas: string[]
  ulangan: string[]
  uas: string
  keterangan: string
}

export interface CsvParseResult {
  rows: CsvSantriRow[]
  errors: { line: number; message: string }[]
  tugasCount: number
  ulanganCount: number
}

// ---------------------------------------------------------------------------
// Download
// ---------------------------------------------------------------------------

/**
 * Generate and trigger download of a pre-filled CSV template.
 *
 * @param santris   Existing santri rows (from the form state)
 * @param tugasCount  Number of tugas columns
 * @param ulanganCount  Number of ulangan columns
 * @param meta  Metadata for the filename
 */
export function downloadNilaiTemplate(
  santris: CsvSantriRow[],
  tugasCount: number,
  ulanganCount: number,
  meta: { kodeKelas: string; kodeMapel: string; tahunAjaran: string; semester: string },
): void {
  const tugasHeaders = Array.from({ length: tugasCount }, (_, i) => `T${i + 1}`)
  const ulanganHeaders = Array.from({ length: ulanganCount }, (_, i) => `UH${i + 1}`)

  const header = ["nomor_induk", "nama_santri", ...tugasHeaders, ...ulanganHeaders, "UAS", "KETERANGAN"]

  const rows = santris.map((s) => {
    const tugas = Array.from({ length: tugasCount }, (_, i) => s.tugas[i] ?? "")
    const ulangan = Array.from({ length: ulanganCount }, (_, i) => s.ulangan[i] ?? "")
    return [s.nomor_induk, s.nama_santri, ...tugas, ...ulangan, s.uas, s.keterangan]
  })

  const csvLines = [header, ...rows].map((row) =>
    row.map((cell) => {
      const str = String(cell ?? "")
      // Quote cells that contain comma, newline, or double quote
      if (str.includes(",") || str.includes("\n") || str.includes('"')) {
        return `"${str.replace(/"/g, '""')}"`
      }
      return str
    }).join(","),
  )

  const csvContent = csvLines.join("\r\n")
  const blob = new Blob(["\uFEFF" + csvContent], { type: "text/csv;charset=utf-8;" })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement("a")
  const safeTahun = meta.tahunAjaran.replace(/\//g, "-")
  anchor.href = url
  anchor.download = `nilai-${meta.kodeKelas}-${meta.kodeMapel}-${safeTahun}-s${meta.semester}.csv`
  anchor.click()
  URL.revokeObjectURL(url)
}

